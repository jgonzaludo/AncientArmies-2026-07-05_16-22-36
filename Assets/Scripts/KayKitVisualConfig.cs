using UnityEngine;

// Switches the soldier visuals between the KayKit animated characters and the
// old capsule placeholders. Lives in Assets/AncientArmies/Visuals/KayKit/Resources
// and is loaded by name (no scene reference needed, so Battle.unity stays untouched).
[CreateAssetMenu(fileName = "KayKitVisualConfig", menuName = "Ancient Armies/KayKit Visual Config")]
public class KayKitVisualConfig : ScriptableObject
{
    [Tooltip("true: animated KayKit soldiers. false: the old capsule + cube placeholders")]
    public bool useKayKitVisual = true;

    [Header("Generated by the KayKit build task (do not edit)")]
    public Material blueMaterial;
    public Material redMaterial;
    public Material bowMaterial;

    [Header("Animation")]
    [Tooltip("Cross-fade length between clips (seconds)")]
    public float crossFade = 0.15f;
    [Tooltip("Walking clip plays at speed = soldier speed / this")]
    public float walkReferenceSpeed = 1.6f;
    [Tooltip("Running clip plays at speed = soldier speed / this")]
    public float runReferenceSpeed = 4.2f;
    [Tooltip("Seconds the bow is drawn before the arrow is released")]
    public float bowDrawSeconds = 0.55f;

    [Header("Distant soldiers")]
    [Tooltip("Soldiers farther than this from the camera update their animator every Nth frame")]
    public float staggerDistance = 70f;
    public int staggerFrames = 3;
}
